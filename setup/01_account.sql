-- -----------------------------------------------------------------------------
-- 1. Hierarchie de roles (support du module RBAC)
--    ACCOUNTADMIN
--      +-- SYSADMIN
--            +-- FORMATION_ADMIN        (proprietaire des objets partages)
--            +-- R_P01..R_Pnn           (un role par participant, 03_participants.sql)
--                  +-- FORMATION_PARTICIPANT (droits communs)
-- -----------------------------------------------------------------------------
USE ROLE USERADMIN;
CREATE ROLE IF NOT EXISTS FORMATION_ADMIN       COMMENT = 'Formateur - proprietaire des objets de formation';
CREATE ROLE IF NOT EXISTS FORMATION_PARTICIPANT COMMENT = 'Droits communs a tous les participants';
GRANT ROLE FORMATION_ADMIN       TO ROLE SYSADMIN;
GRANT ROLE FORMATION_PARTICIPANT TO ROLE FORMATION_ADMIN;
SET me = CURRENT_USER();
GRANT ROLE FORMATION_ADMIN       TO USER IDENTIFIER($me);

-- -----------------------------------------------------------------------------
-- 2. Warehouses partages (auto-suspend 60 s pour preserver les credits)
-- -----------------------------------------------------------------------------
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS WH_ADMIN
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Formateur / scripts de setup';
CREATE WAREHOUSE IF NOT EXISTS WH_PERF_DEMO
  WAREHOUSE_SIZE = SMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Demo performance (resize, cache, multi-cluster)';
GRANT OWNERSHIP ON WAREHOUSE WH_ADMIN     TO ROLE FORMATION_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON WAREHOUSE WH_PERF_DEMO TO ROLE FORMATION_ADMIN COPY CURRENT GRANTS;

-- -----------------------------------------------------------------------------
-- 3. Bases
--    FORMATION : donnees partagees (RAW -> CURATED), objets d'integration (COMMON)
--    SANDBOX   : un schema par participant, dont il est proprietaire
--    ADMIN     : Git (repo de formation) et SECURITY (policies transverses)
-- -----------------------------------------------------------------------------
CREATE DATABASE IF NOT EXISTS FORMATION COMMENT = 'Donnees et objets partages de la formation';
CREATE DATABASE IF NOT EXISTS SANDBOX   COMMENT = 'Espaces de travail des participants';
GRANT OWNERSHIP ON DATABASE FORMATION TO ROLE FORMATION_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE SANDBOX   TO ROLE FORMATION_ADMIN COPY CURRENT GRANTS;

CREATE DATABASE IF NOT EXISTS ADMIN COMMENT = 'Database for administration';

-- -----------------------------------------------------------------------------
-- 4. Schema ADMIN.GIT
--    L'API INTEGRATION et le GIT REPOSITORY sont crees par 00_bootstrap_git.sql.
--    Roles techniques : _SR (lecture) -> _SW -> _SFULL -> SYSADMIN
-- -----------------------------------------------------------------------------
USE ROLE SYSADMIN;
CREATE SCHEMA IF NOT EXISTS ADMIN.GIT WITH MANAGED ACCESS
  COMMENT = 'Git repositories & secrets for CI/CD (dbt project sync)';

USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS _ADMIN_GIT_SR;
CREATE ROLE IF NOT EXISTS _ADMIN_GIT_SW;
CREATE ROLE IF NOT EXISTS _ADMIN_GIT_SFULL;

GRANT ROLE _ADMIN_GIT_SR    TO ROLE _ADMIN_GIT_SW;
GRANT ROLE _ADMIN_GIT_SW    TO ROLE _ADMIN_GIT_SFULL;
GRANT ROLE _ADMIN_GIT_SFULL TO ROLE SYSADMIN;

-- Les participants lisent le repo (ouverture des labs dans Snowsight, dbt project).
GRANT ROLE _ADMIN_GIT_SFULL TO ROLE FORMATION_ADMIN;
GRANT ROLE _ADMIN_GIT_SR    TO ROLE FORMATION_PARTICIPANT;

USE ROLE SYSADMIN;
GRANT USAGE ON DATABASE ADMIN   TO ROLE _ADMIN_GIT_SR;
GRANT USAGE ON SCHEMA ADMIN.GIT TO ROLE _ADMIN_GIT_SR;
GRANT USAGE ON FUTURE SECRETS IN SCHEMA ADMIN.GIT TO ROLE _ADMIN_GIT_SR;
GRANT READ  ON GIT REPOSITORY ADMIN.GIT.TRAINING_REPO TO ROLE _ADMIN_GIT_SR;

GRANT CREATE GIT REPOSITORY ON SCHEMA ADMIN.GIT TO ROLE _ADMIN_GIT_SFULL;
GRANT CREATE SECRET         ON SCHEMA ADMIN.GIT TO ROLE _ADMIN_GIT_SFULL;
-- WRITE = ALTER GIT REPOSITORY ... FETCH par le formateur
GRANT WRITE ON GIT REPOSITORY ADMIN.GIT.TRAINING_REPO TO ROLE _ADMIN_GIT_SFULL;

-- -----------------------------------------------------------------------------
-- 5. Schema ADMIN.SECURITY (policies / tags transverses)
-- -----------------------------------------------------------------------------
USE ROLE SYSADMIN;
CREATE SCHEMA IF NOT EXISTS ADMIN.SECURITY WITH MANAGED ACCESS DATA_RETENTION_TIME_IN_DAYS = 30
  COMMENT = 'Schema SECURITY for rules and policies';

USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS _ADMIN_SECURITY_SR;
CREATE ROLE IF NOT EXISTS _ADMIN_SECURITY_SW;
CREATE ROLE IF NOT EXISTS _ADMIN_SECURITY_SFULL;

GRANT ROLE _ADMIN_SECURITY_SR    TO ROLE _ADMIN_SECURITY_SW;
GRANT ROLE _ADMIN_SECURITY_SW    TO ROLE _ADMIN_SECURITY_SFULL;
GRANT ROLE _ADMIN_SECURITY_SFULL TO ROLE SYSADMIN;

GRANT ROLE _ADMIN_SECURITY_SR    TO ROLE FORMATION_PARTICIPANT;
GRANT ROLE _ADMIN_SECURITY_SFULL TO ROLE FORMATION_ADMIN;

/*SR for read access*/
USE ROLE SYSADMIN;
GRANT USAGE ON DATABASE ADMIN TO ROLE _ADMIN_SECURITY_SR;
GRANT USAGE ON SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SR;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SR;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SR;
GRANT SELECT ON FUTURE STREAMS IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SR;
GRANT SELECT ON FUTURE MATERIALIZED VIEWS IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SR;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SR;
GRANT USAGE, READ ON FUTURE STAGES IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SR;
GRANT USAGE ON FUTURE FILE FORMATS IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SR;
GRANT USAGE ON FUTURE PROCEDURES IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SR;
GRANT USAGE ON FUTURE FUNCTIONS IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SR;
GRANT USAGE ON FUTURE SEQUENCES IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SR;

/*SW for write access*/
GRANT INSERT, UPDATE, TRUNCATE, REFERENCES, DELETE ON FUTURE TABLES IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SW;
GRANT READ, WRITE ON FUTURE STAGES IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SW;
GRANT MONITOR, OPERATE ON FUTURE TASKS IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SW;

/*SFULL for full access*/
GRANT CREATE TABLE, CREATE VIEW, CREATE FILE FORMAT ON SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SFULL;
GRANT OWNERSHIP ON FUTURE TABLES IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SFULL;
GRANT OWNERSHIP ON FUTURE VIEWS IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SFULL;
GRANT OWNERSHIP ON FUTURE STAGES IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SFULL;
GRANT OWNERSHIP ON FUTURE FILE FORMATS IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SFULL;
GRANT OWNERSHIP ON FUTURE STREAMS IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SFULL;
GRANT OWNERSHIP ON FUTURE PROCEDURES IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SFULL;
GRANT OWNERSHIP ON FUTURE FUNCTIONS IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SFULL;
GRANT OWNERSHIP ON FUTURE SEQUENCES IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SFULL;
GRANT OWNERSHIP ON FUTURE TASKS IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SFULL;
GRANT OWNERSHIP ON FUTURE MATERIALIZED VIEWS IN SCHEMA ADMIN.SECURITY TO ROLE _ADMIN_SECURITY_SFULL;
