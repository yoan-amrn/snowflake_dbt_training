USE ROLE ACCOUNTADMIN;

-- -----------------------------------------------------------------------------
-- 0. Parametres compte
-- -----------------------------------------------------------------------------
ALTER ACCOUNT SET TIMEZONE = 'Europe/Paris';
-- Cortex : si la region du trial ne sert pas tous les modeles, autoriser l'inference
